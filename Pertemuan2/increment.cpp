#include <iostream>
using namespace std;

int main() {
  int c;
  cout << "\n== Materi Increment dan Decrement" << endl;
  cout << "Masukkan angka awal untuk C: " << endl;
  cin >> c;

  cout << "Nilai C untuk saat ini: " << c << endl;
  cout << "Nilai ++C untuk Increment: " << ++c << endl;
  cout << "Nilai C Setelah pre-increment: " << c << endl;

  return 0;
}
